package main

import "image/color"

// Family pixel art, 48x48 HD (artgen_hd.py). Full-bleed glyphs in
// each program's own colors - no shield frames. Light/dark variant
// chars are generated bevel shades of the base palette.
type progArtDef struct {
	grid []string
	pal  map[byte]color.NRGBA
}

func artPal(m map[byte]string) map[byte]color.NRGBA {
	out := make(map[byte]color.NRGBA, len(m))
	for k, hx := range m {
		out[k] = color.NRGBA{hx2b(hx[0:2]), hx2b(hx[2:4]), hx2b(hx[4:6]), 0xFF}
	}
	return out
}

func hx2b(s string) uint8 {
	var v uint8
	for _, ch := range s {
		v <<= 4
		switch {
		case ch >= '0' && ch <= '9':
			v |= uint8(ch - '0')
		case ch >= 'A' && ch <= 'F':
			v |= uint8(ch - 'A' + 10)
		case ch >= 'a' && ch <= 'f':
			v |= uint8(ch - 'a' + 10)
		}
	}
	return v
}

